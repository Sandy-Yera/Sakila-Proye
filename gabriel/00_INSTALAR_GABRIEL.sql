BEGIN
    FOR R_OBJETO IN (
        SELECT OBJECT_NAME, OBJECT_TYPE
        FROM USER_OBJECTS
        WHERE OBJECT_TYPE IN ('PACKAGE', 'PROCEDURE', 'FUNCTION', 'TABLE')
          AND OBJECT_NAME IN ('PKG_RESPONSABILIDAD_CLIENTE', 'SP_ACTUALIZA_MEDALLAS',
                              'FN_PUEDE_ARRENDAR', 'SP_MEDALLA_CLIENTE',
                              'FN_PORCENTAJE_EN_PLAZO', 'FN_FECHA_CORTE', 'CLIENTE_MEDALLA')
    ) LOOP
        EXECUTE IMMEDIATE 'DROP ' || R_OBJETO.OBJECT_TYPE || ' ' || R_OBJETO.OBJECT_NAME
            || CASE WHEN R_OBJETO.OBJECT_TYPE = 'TABLE' THEN ' CASCADE CONSTRAINTS' END;
    END LOOP;
END;
/

EXEC DBMS_STATS.GATHER_SCHEMA_STATS(USER, NO_INVALIDATE => FALSE)

