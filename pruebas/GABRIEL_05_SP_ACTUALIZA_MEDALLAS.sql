SELECT MEDALLA,
       COUNT(*)                          AS CLIENTES,
       ROUND(AVG(PORCENTAJE_EN_PLAZO), 1) AS PORCENTAJE_PROMEDIO
FROM CLIENTE_MEDALLA
GROUP BY MEDALLA
ORDER BY PORCENTAJE_PROMEDIO DESC;

ROLLBACK;

SELECT COUNT(*) AS FILAS_TRAS_ROLLBACK
FROM CLIENTE_MEDALLA;
